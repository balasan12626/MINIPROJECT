"""F6 — serve the stored route-choice benchmark. The benchmark itself is NEVER
run inside a request: generate it with scripts/bench_routes.py."""

import json
from pathlib import Path

from fastapi import APIRouter, HTTPException

router = APIRouter()

MODELS = Path(__file__).resolve().parents[2] / "models"
RESULT = MODELS / "route_benchmark_v1.json"
TIMING = MODELS / "route_benchmark_v1.timing.json"


@router.get("/api/benchmark/ops")
async def ops_benchmark(city: str | None = None):
    """F12 — stored Monte-Carlo evaluation of the rescue operation for a city
    (scripts/monte_carlo_ops.py). Never run inside a request."""
    available = sorted(p.stem.removeprefix("ops_montecarlo_v1_") for p in MODELS.glob("ops_montecarlo_v1_*.json")
                       if not p.stem.endswith(".timing"))
    if not available:
        raise HTTPException(404, "Ops benchmark not generated yet - run: python scripts/monte_carlo_ops.py --city delhi")
    city = city or ("delhi" if "delhi" in available else available[0])
    if not city.isidentifier() or city not in available:
        raise HTTPException(404, f"No ops benchmark for {city} - run: python scripts/monte_carlo_ops.py --city {city}")
    path = MODELS / f"ops_montecarlo_v1_{city}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    timing = path.with_suffix(".timing.json")
    data["timing"] = json.loads(timing.read_text(encoding="utf-8")) if timing.exists() else None
    data["available_cities"] = available
    return data


def _files(city: str | None):
    if not city or city == "delhi_seed":
        return RESULT, TIMING
    if not city.isidentifier():
        raise HTTPException(400, "bad city id")
    res = MODELS / f"route_benchmark_v1_{city}.json"
    return res, res.with_suffix(".timing.json")


@router.get("/api/benchmark/routes")
async def route_benchmark(details: bool = False, city: str | None = None):
    """Summary per blockage level (add ?details=true for every synthetic trip).
    `city` picks a real-city run (F7); default is the demo network."""
    result, timing = _files(city)
    if not result.exists():
        hint = f" --city {city}" if city else ""
        raise HTTPException(404, f"Route benchmark not generated yet - run: python scripts/bench_routes.py{hint}")
    data = json.loads(result.read_text(encoding="utf-8"))
    if not details:
        data = {**data, "trips": None, "levels": [{k: v for k, v in lv.items() if k != "per_trip"} for lv in data["levels"]]}
    data["timing"] = json.loads(timing.read_text(encoding="utf-8")) if timing.exists() else None
    data["available_cities"] = sorted(
        ["delhi_seed"] * RESULT.exists() + [p.stem.removeprefix("route_benchmark_v1_") for p in MODELS.glob("route_benchmark_v1_*.json")
                                             if not p.stem.endswith(".timing")]
    )
    return data


# Stored measured results of later features — each generated by a script, never in a request.
STORED = {
    "ops_warning_sweep_v1": "python scripts/monte_carlo_ops.py --city {city} --compliance 0,0.2,0.4,0.6",  # F23
    "ops_long_v1": "python scripts/monte_carlo_ops.py --city {city} --long",  # F25
    "ops_fairness_v1": "python scripts/monte_carlo_ops.py --city {city} --fair-lambdas 0,0.5,1,2,4",  # F32
    "ops_sensitivity_v1": "python scripts/sensitivity_ops.py --city {city}",  # F33
    "ops_regret_v1": "python scripts/regret_runs.py",  # F34 (all stored runs, no city)
    "closure_validation_v1": "python scripts/validate_closures.py --city {city}",  # F20
    "hand_compare_v1": "python scripts/build_hand.py --city {city}",  # F26
    "ai_eval_v1": "python scripts/eval_ai_assistant.py",  # F35 (no city)
}


@router.get("/api/benchmark/stored/{name}")
async def stored_result(name: str, city: str | None = None):
    """One stored result file: models/<name>_<city>.json (or models/<name>.json)."""
    if name not in STORED:
        raise HTTPException(404, f"unknown result {name}")
    per_city = sorted(p.stem.removeprefix(f"{name}_") for p in MODELS.glob(f"{name}_*.json") if not p.stem.endswith(".timing"))
    single = MODELS / f"{name}.json"
    if city:
        if not city.isidentifier():
            raise HTTPException(400, "bad city id")
        path = MODELS / f"{name}_{city}.json"
    elif single.exists():
        path = single
    else:
        path = MODELS / f"{name}_{per_city[0]}.json" if per_city else single
    if not path.exists():
        raise HTTPException(404, f"Not generated yet - run: {STORED[name].format(city=city or 'delhi')}")
    data = json.loads(path.read_text(encoding="utf-8"))
    data["available_cities"] = per_city
    return data
