"""Build the IEEE paper series (P1 quantum, P2 agentic, P3 agentic+quantum) and collect P4.

  python build_series.py [p1 p2 p3] [--word]
Needs the experiment JSONs in the work dir (run p*/exp_p*.py with the repo .venv first),
MiKTeX pdflatex + IEEEtran, Poppler (pdfinfo, pdffonts, pdftotext), matplotlib.
Every number in a paper comes from nums.tex, generated by p*/post_p*.py from the JSON;
post scripts also assert the qualitative claims made in the text.
Output: "iee papper fineal/series/<PaperN_...>/".
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
import os  # noqa: E402

WORK = Path(os.environ.get("PAPER_SERIES_WORK", Path(os.environ["TEMP"]) / "aquasentinel-series"))
OUT = ROOT / "iee papper fineal" / "series"
MAX_PAGES = int(os.environ.get("PAPER_MAX_PAGES", "8"))  # INDICON-type venues: set 6
PAPERS = {
    "p1": ("p1_quantum", "Paper1_Quantum_QAOA"),
    "p2": ("p2_agentic", "Paper2_Agentic_AI"),
    "p3": ("p3_qagentic", "Paper3_Agentic_Quantum"),
    "p4": ("p4_forecast", "Paper4_Forecasting_CAMELS_IND"),
    "p5": ("p5_merged", "Paper5_Merged_FailClosed_Chain"),
}
AUTHOR_TOKENS = (r"\bSona\b", "gmail", r"\bSalem\b", "github", "Nandhakumar", "Balakarthikeyan", "Gowthaman",
                 "Abhishek", "AquaSentinel")
BLIND = ("\\author{\\IEEEauthorblockN{Anonymous Author(s)}\n"
         "\\IEEEauthorblockA{\\textit{Affiliation withheld for double-blind review}}}")


def run(cmd, cwd=None, check=True):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, shell=isinstance(cmd, str))
    if check and r.returncode:
        raise SystemExit(f"FAILED: {cmd}\n{r.stdout[-2000:]}\n{r.stderr[-2000:]}")
    return r


def build(key: str, word: bool) -> list[str]:
    src_dir, name = PAPERS[key]
    src = HERE / src_dir
    pdir = WORK / key
    pdir.mkdir(parents=True, exist_ok=True)
    run([sys.executable, str(src / f"post_{key}.py"), str(WORK), str(pdir)])
    tex = (src / "paper.tex").read_text(encoding="utf-8")
    # generated table rows are inlined: \input inside a booktabs tabular breaks \bottomrule
    tex = re.sub(r"\\input\{(tab_[a-z_]+)\.tex\}",
                 lambda m: (pdir / f"{m.group(1)}.tex").read_text(encoding="utf-8"), tex)
    a, b = tex.index("%<AUTHORS>"), tex.index("%</AUTHORS>") + len("%</AUTHORS>")
    (pdir / "camera.tex").write_text(tex, encoding="utf-8")
    (pdir / "blind.tex").write_text(tex[:a] + BLIND + tex[b:], encoding="utf-8")
    fails = []
    for f in ("blind", "camera"):
        (pdir / f"{f}.pdf").unlink(missing_ok=True)
        for _ in range(2):
            run(f'cmd /c "pdflatex -interaction=nonstopmode {f}.tex >nul 2>&1"', cwd=pdir, check=False)
        if not (pdir / f"{f}.pdf").exists():
            raise SystemExit(f"pdflatex failed: {pdir / (f + '.log')}")
        log = (pdir / f"{f}.log").read_text(encoding="latin-1")
        for pat in ("Undefined control sequence", "There were undefined references", "Citation `", "LaTeX Error"):
            if pat in log:
                fails.append(f"{f}.log: {pat}")
        info = run(["pdfinfo", str(pdir / f"{f}.pdf")]).stdout
        pages = int(re.search(r"Pages:\s+(\d+)", info).group(1))
        if pages > MAX_PAGES:
            fails.append(f"{f}.pdf: {pages} pages (limit {MAX_PAGES})")
        fonts = run(["pdffonts", str(pdir / f"{f}.pdf")]).stdout.splitlines()[2:]
        if any("Type 3" in x for x in fonts):
            fails.append(f"{f}.pdf: Type 3 font")
        if any(len(x.split()) >= 5 and x.split()[-5] == "no" for x in fonts):
            fails.append(f"{f}.pdf: font not embedded")
        txt = subprocess.run(["pdftotext", "-enc", "UTF-8", str(pdir / f"{f}.pdf"), "-"],
                             capture_output=True).stdout.decode("utf-8", "ignore")
        if "??" in txt:
            fails.append(f"{f}.pdf: unresolved reference (??)")
        for broken in ("extit", "extbf", "extsc", "egin{", "\\cite", "\\ref"):
            if broken in txt:
                fails.append(f"{f}.pdf: broken LaTeX command in output text ('{broken}')")
        if f == "blind":
            for pat in AUTHOR_TOKENS:
                if re.search(pat, txt, re.I):
                    fails.append(f"blind.pdf identifies authors: '{pat}'")
        print(f"  {key} {f}.pdf: {pages} pages")
    for pat in ("TODO", "XXX", "example values", "representative"):
        if pat.lower() in tex.lower():
            fails.append(f"placeholder text: {pat}")
    dst = OUT / name
    dst.mkdir(parents=True, exist_ok=True)
    shutil.copy(pdir / "blind.pdf", dst / "SUBMIT_blind_review.pdf")
    shutil.copy(pdir / "blind.tex", dst / "SUBMIT_blind_review.tex")
    shutil.copy(pdir / "camera.pdf", dst / "camera_ready_with_authors.pdf")
    shutil.copy(pdir / "camera.tex", dst / "camera_ready_with_authors.tex")
    shutil.copy(pdir / "nums.tex", dst / "nums.tex")
    for fig in pdir.glob("fig_*.pdf"):
        shutil.copy(fig, dst / fig.name)
    shutil.copy(WORK / f"{key}.json", dst / f"{key}_results.json")
    if word:
        for f, n in (("blind", "SUBMIT_blind_review"), ("camera", "camera_ready_with_authors")):
            ps = (f"$w=New-Object -ComObject Word.Application;$w.Visible=$false;$w.DisplayAlerts=0;"
                  f"try{{$d=$w.Documents.Open('{pdir / (f + '.pdf')}',$false,$true);"
                  f"$d.SaveAs2('{dst / (n + '.docx')}',16);$d.Close($false)}}finally{{$w.Quit()}}")
            r = run(["powershell", "-NoProfile", "-Command", ps], check=False)
            print(f"  {key} {n}.docx: {'ok' if (dst / (n + '.docx')).exists() else 'FAILED ' + r.stderr[-300:]}")
    return fails


def collect_p4():
    src = ROOT / "iee papper fineal" / "revised"
    dst = OUT / "Paper4_FullScenario_FailClosed"
    dst.mkdir(parents=True, exist_ok=True)
    for f in ("SUBMIT_blind_review.pdf", "SUBMIT_blind_review.docx", "SUBMIT_blind_review.tex",
              "camera_ready_with_authors.pdf", "camera_ready_with_authors.docx", "camera_ready_with_authors.tex",
              "fig_safety.pdf", "exp.json"):
        if (src / f).exists():
            shutil.copy(src / f, dst / f)
    print("  p4 collected from", src)


if __name__ == "__main__":
    keys = [a for a in sys.argv[1:] if a in PAPERS] or list(PAPERS)
    word = "--word" in sys.argv
    all_fails = []
    for k in keys:
        print(f"building {k}")
        all_fails += [f"{k}: {x}" for x in build(k, word)]
    collect_p4()
    audit = run([sys.executable, str(HERE / "audit_refs.py")], check=False)
    print(audit.stdout.strip())
    if "REFERENCES OK" not in audit.stdout:
        all_fails.append("reference/label audit failed")
    print("\n".join("FAIL " + f for f in all_fails) if all_fails else "ALL CHECKS PASSED")
    sys.exit(1 if all_fails else 0)
